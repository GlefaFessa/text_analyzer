def get_info(key: str) -> dict:
    """Возвращает описание метрики по её ключу.

    Для метрик StyloMetrix, которых нет в METRIC_INFO,
    генерирует описание на основе префикса.
    Для полностью неизвестных — возвращает пустой словарь,
    и UI покажет только имя метрики.
    """
    # Точное совпадение — приоритет.
    if key in METRIC_INFO:
        return METRIC_INFO[key]

    # Fallback для StyloMetrix.
    if key.startswith("stylometry."):
        short_key = key[len("stylometry."):]
        for prefix, (name, full) in STYLOMETRY_PREFIXES.items():
            if short_key.startswith(prefix):
                return {
                    "name": short_key,
                    "short": f"{name}: {full}",
                    "full": (
                        f"Метрика {short_key} из библиотеки StyloMetrix. "
                        f"Категория: {name}. {full} "
                        "Подробнее: https://github.com/ZILiAT-NASK/StyloMetrix"
                    ),
                    "wiki": "https://github.com/ZILiAT-NASK/StyloMetrix",
                }
        # Метрика StyloMetrix без известного префикса.
        return {
            "name": short_key,
            "short": "Метрика StyloMetrix",
            "full": "Описание не найдено. См. документацию StyloMetrix.",
            "wiki": "https://github.com/ZILiAT-NASK/StyloMetrix",
        }

    # Совсем неизвестный ключ.
    return {}