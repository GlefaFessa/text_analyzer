_MORPH_RU = None


def _get_morph_ru():
    global _MORPH_RU
    if _MORPH_RU is None:
        import pymorphy3
        _MORPH_RU = pymorphy3.MorphAnalyzer()
    return _MORPH_RU


def _get_stopwords(lang: str) -> set:
    return STOPWORDS_RU if lang == "ru" else STOPWORDS_EN


def _lemmatize(text: str, lang: str) -> list:
    """Лемматизация с фильтрацией не-буквенных токенов."""
    tokens = [w.lower() for w in words(text)]
    if not tokens:
        return []

    if lang == "ru":
        morph = _get_morph_ru()
        return [morph.parse(t)[0].normal_form for t in tokens]
    else:
        from .morphology import _get_nlp_en
        nlp = _get_nlp_en()
        doc = nlp(" ".join(tokens))
        return [t.lemma_.lower() for t in doc if t.is_alpha]


def _empty_result() -> dict:
    return {
        "seo.tokens": 0,
        "seo.water_count": 0,
        "seo.water_ratio": 0.0,
        "seo.spam_ratio": 0.0,
        "seo.max_word_freq": 0,
        "seo.classic_nausea": 0.0,
        "seo.academic_nausea": 0.0,
    }


def compute(text: str, lang: str = "ru") -> dict:
    """SEO-метрики для текста."""
    src = clean(text)
    tokens = _lemmatize(src, lang)
    n = len(tokens)
    if n == 0:
        return _empty_result()

    stopwords = _get_stopwords(lang)
    freq = Counter(tokens)

    # Водность — доля стоп-слов.
    water_count = sum(1 for t in tokens if t in stopwords)
    water_ratio = water_count / n * 100

    # Заспамленность — доля топ-10 слов.
    top10_count = sum(c for _, c in freq.most_common(10))
    spam_ratio = top10_count / n * 100

    # Тошнота.
    max_freq = max(freq.values())
    classic_nausea = sqrt(max_freq)
    academic_nausea = max_freq / n * 100

    return {
        "seo.tokens": n,
        "seo.water_count": water_count,
        "seo.water_ratio": water_ratio,
        "seo.spam_ratio": spam_ratio,
        "seo.max_word_freq": max_freq,
        "seo.classic_nausea": classic_nausea,
        "seo.academic_nausea": academic_nausea,
    }


def keywords(text: str, lang: str = "ru", top: int = 20) -> list:
    """Топ ключевых слов — по леммам, без стоп-слов.

    Возвращает список пар (слово, частота), упорядоченный по убыванию.
    Это структура, а не скаляр, поэтому вынесена отдельно от compute.
    """
    src = clean(text)
    tokens = _lemmatize(src, lang)
    stopwords = _get_stopwords(lang)
    freq = Counter(t for t in tokens if t not in stopwords)
    return freq.most_common(top)