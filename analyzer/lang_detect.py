"""Простое определение языка текста по алфавиту.

Поддерживается только пара ru/en. Для двух языков с разными алфавитами
(кириллица vs латиница) сложные статистические модели не нужны:
достаточно подсчитать долю букв каждого алфавита.

Для расширения на другие языки (de, fr, es — все на латинице)
этот подход не сработает, потребуется langdetect или аналог.
"""


def _is_cyrillic(ch: str) -> bool:
    """True для букв кириллицы в Unicode."""
    code = ord(ch)
    # Основной блок + дополнение + расширенный-A.
    return (
        0x0400 <= code <= 0x04FF      # Кириллица (основной)
        or 0x0500 <= code <= 0x052F   # Кириллица (дополнение)
        or 0x2DE0 <= code <= 0x2DFF   # Кириллица (расширение-A)
    )


def _is_latin(ch: str) -> bool:
    """True для букв латиницы в Unicode."""
    code = ord(ch)
    return (
        0x0041 <= code <= 0x005A     # A-Z
        or 0x0061 <= code <= 0x007A  # a-z
        or 0x00C0 <= code <= 0x024F  # расширенная латиница (диакритика)
    )


def detect(text: str) -> str:
    """Определяет язык текста: 'ru', 'en' или 'unknown'.

    Логика: считаем кириллические и латинские буквы, берём ту,
    которой больше. Знаки препинания, цифры и пробелы игнорируются.

    Для пустого текста или текста без букв возвращает 'unknown'.
    """
    cyr = 0
    lat = 0
    for ch in text:
        if _is_cyrillic(ch):
            cyr += 1
        elif _is_latin(ch):
            lat += 1

    total = cyr + lat
    if total == 0:
        return "unknown"

    # Если одного алфавита подавляющее большинство (>80%) — уверенно выбираем.
    # Если текст смешанный — всё равно возвращаем доминирующий, но это
    # можно использовать в UI, чтобы показать предупреждение.
    if cyr > lat:
        return "ru"
    if lat > cyr:
        return "en"
    return "unknown"


def confidence(text: str) -> float:
    """Уверенность определения: доля доминирующего алфавита.

    1.0 — текст полностью на одном алфавите.
    0.5 — равное количество кириллицы и латиницы (смешанный текст).
    0.0 — букв нет вообще.
    """
    cyr = sum(1 for ch in text if _is_cyrillic(ch))
    lat = sum(1 for ch in text if _is_latin(ch))
    total = cyr + lat
    if total == 0:
        return 0.0
    return max(cyr, lat) / total